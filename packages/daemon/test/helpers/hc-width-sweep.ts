// OF-231: the cell widths the hc core gives characters, read back from a PRIVATE core (helpers/hc-scratch.ts; the host's core is never contacted).
// A program in a terminal writes `a`, the character, and a cursor-position request (CSI 6 n) and reads the core's reply from its stdin: the
// reply's column minus 2 is the character's width in cells. Requests are pipelined (400 per round trip), so all 1,111,999 code points
// (U+0020..U+10FFFF, less DEL, C1 and surrogates) take about two seconds. `a` goes first so a combining mark has a cell to follow.
import fs from "node:fs";
import path from "node:path";
import type { HcScratch } from "./hc-scratch.js";
import { until } from "./pi-runner-pane.js";

const PROBE_PROGRAM = `
const fs = require("node:fs");
const out = process.env.PROBE_OUT;
const seqs = process.env.PROBE_SEQS ? JSON.parse(process.env.PROBE_SEQS) : null;
process.stdin.setRawMode(true); process.stdin.resume();
let buf = "", want = 0, done = null;
const got = [];
process.stdin.on("data", (d) => {
  buf += d.toString("latin1");
  const re = /\\x1b\\[(\\d+);(\\d+)R/g; let m, last = 0;
  while ((m = re.exec(buf))) { got.push(+m[2]); last = re.lastIndex; }
  buf = buf.slice(last);
  if (done && got.length >= want) { const d = done; done = null; d(); }
});
function ask(items) {
  got.length = 0; want = items.length;
  return new Promise((resolve) => { done = resolve; process.stdout.write(items.map((s) => "\\x1b[1;1H\\x1b[2K" + "a" + s + "\\x1b[6n").join("")); });
}
(async () => {
  if (seqs) {
    await ask(seqs);
    fs.writeFileSync(out, JSON.stringify(got.map((c) => c - 2)));
  } else {
    const widths = Buffer.alloc(0x110000, 255);
    let items = [], cps = [];
    const flush = async () => { if (!items.length) return; await ask(items); cps.forEach((cp, i) => { widths[cp] = got[i] - 2; }); items = []; cps = []; };
    for (let cp = 0x20; cp <= 0x10ffff; cp++) {
      if ((cp >= 0x7f && cp <= 0x9f) || (cp >= 0xd800 && cp <= 0xdfff)) continue;
      items.push(String.fromCodePoint(cp)); cps.push(cp);
      if (items.length >= 400) await flush();
    }
    await flush();
    fs.writeFileSync(out, widths);
  }
  setInterval(() => undefined, 1000);
})();
`;

let probes = 0;
async function runProbe(scratch: HcScratch, name: string, seqs: string[] | null, timeoutMs: number): Promise<Buffer> {
  const dir = fs.mkdtempSync(path.join(scratch.root, "ws-"));
  const script = path.join(dir, "probe.cjs");
  const out = path.join(dir, "out.bin");
  fs.writeFileSync(script, PROBE_PROGRAM);
  await scratch.client().call("terminal.run", {
    argv: [process.execPath, script], name: `${name}-${++probes}`, cwd: dir,
    env: { PATH: path.dirname(process.execPath), PROBE_OUT: out, ...(seqs ? { PROBE_SEQS: JSON.stringify(seqs) } : {}) },
    no_parent: true, no_notify: true, outlive_parent: true,
  });
  await until(async () => fs.existsSync(out), (v) => v, `the width probe ${name} to finish`, timeoutMs);
  return fs.readFileSync(out);
}

/** The core's width of every code point: index = code point, value 0, 1 or 2; 255 for a code point not asked (below U+0020, DEL, C1, surrogates). */
export async function sweepCoreWidths(scratch: HcScratch): Promise<Uint8Array> {
  return new Uint8Array(await runProbe(scratch, "sweep", null, 120_000));
}

/** The cells the cursor advances for `a` + each string (minus the `a`): a sequence's width as the core draws it. */
export async function coreSequenceWidths(scratch: HcScratch, sequences: string[]): Promise<number[]> {
  return JSON.parse((await runProbe(scratch, "seq", sequences, 60_000)).toString("utf8")) as number[];
}

/** Maximal runs of consecutive code points whose measured width is `width`, as [first, last] pairs, ascending. */
export function rangesOfWidth(widths: Uint8Array, width: number): Array<[number, number]> {
  const ranges: Array<[number, number]> = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const hit = cp < 0x110000 && widths[cp] === width;
    if (hit && start < 0) start = cp;
    if (!hit && start >= 0) { ranges.push([start, cp - 1]); start = -1; }
  }
  return ranges;
}

/** The text of src/adapters/runner-pane-width-table.ts for the widths a core gave (`version` is `hc --version`). */
export function paneWidthTableSource(widths: Uint8Array, version: string): string {
  const flat = (ranges: Array<[number, number]>) => {
    const items = ranges.flat().map((n) => `0x${n.toString(16)}`);
    const lines: string[] = [];
    for (let i = 0; i < items.length; i += 8) lines.push(`  ${items.slice(i, i + 8).join(", ")},`);
    return lines.join("\n");
  };
  const zero = rangesOfWidth(widths, 0);
  const wide = rangesOfWidth(widths, 2);
  return `// GENERATED by runner-pane-width.real.test.ts (OF-231; OPENRIG_WRITE_PANE_WIDTH_TABLE=1) from a private hc core: ${version}, ${process.platform}. Do not edit by hand.
// The cells the core draws each code point in (U+0020..U+10FFFF): ranges not listed here are 1 cell. Flat [first, last] pairs, ascending.
// ${zero.length} zero-width ranges, ${wide.length} two-cell ranges.

/** Code points the core draws in no cell (combining and other marks, joiners, variation selectors, tags, format characters). */
export const ZERO_WIDTH_RANGES: readonly number[] = [
${flat(zero)}
];

/** Code points the core draws in two cells (East Asian wide and fullwidth, Emoji_Presentation emoji). */
export const WIDE_RANGES: readonly number[] = [
${flat(wide)}
];
`;
}
